#!/usr/bin/env python3
# build_web.py  -  packs website/ into the ESP32 sketch, so the board serves the dashboard itself
#
# Every file under website/ is gzipped and written as a byte array into
# SmartFactoryBoard_MQTT/web_files.h; the sketch sends it with "Content-Encoding: gzip".
# Run it again after changing anything in website/, then upload the sketch:
#
#     python3 esp32/build_web.py          (from the OEE-System folder)

import gzip
import mimetypes
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SITE = HERE.parent / "website"
OUT = HERE / "SmartFactoryBoard_MQTT" / "web_files.h"

TYPES = {".html": "text/html", ".css": "text/css", ".js": "application/javascript", ".svg": "image/svg+xml"}


def main():
    files = sorted(p for p in SITE.rglob("*") if p.is_file() and p.name != ".DS_Store")
    lines = [
        "// web_files.h  -  generated by esp32/build_web.py from website/, do not edit by hand",
        "#pragma once",
        "",
        "struct WebFile { const char* path; const char* type; const uint8_t* data; size_t len; };",
        "",
    ]
    table, total = [], 0
    for i, p in enumerate(files):
        data = gzip.compress(p.read_bytes(), compresslevel=9, mtime=0)
        total += len(data)
        path = "/" + p.relative_to(SITE).as_posix()
        kind = TYPES.get(p.suffix) or mimetypes.guess_type(p.name)[0] or "application/octet-stream"
        lines.append(f"// {path}  ({p.stat().st_size} bytes, {len(data)} gzipped)")
        lines.append(f"static const uint8_t web_{i}[] PROGMEM = {{")
        for k in range(0, len(data), 40):
            lines.append(",".join(str(b) for b in data[k:k + 40]) + ",")
        lines.append("};")
        table.append(f'  {{"{path}", "{kind}", web_{i}, {len(data)}}},')
    lines += ["", "static const WebFile WEB_FILES[] = {", *table, "};",
              "static const size_t WEB_FILE_COUNT = sizeof(WEB_FILES) / sizeof(WEB_FILES[0]);", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(files)} files, {total / 1024:.0f} KB gzipped -> {OUT.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
